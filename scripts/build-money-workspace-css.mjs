#!/usr/bin/env node
// Deterministic shared-panel CSS; page builders retain their scoped source files.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const files=['money-ios.css',...'accounts credit payments connections banks next fundability plan helper strategy alerts declines setup transfers vault'.split(' ').map(key=>`money-${key}-ios.css`)];
const output='/* Generated by scripts/build-money-workspace-css.mjs. Edit section source CSS. */\n'+files.map(file=>`\n/* ${file} */\n`+fs.readFileSync(path.join(root,'public/app',file),'utf8')).join('\n');
const dest=path.join(root,'public/app/money-workspace.css');
if(process.argv.includes('--check')){
 if(!fs.existsSync(dest)||fs.readFileSync(dest,'utf8')!==output){console.error('Money workspace CSS is stale');process.exit(1);}
}else fs.writeFileSync(dest,output);
