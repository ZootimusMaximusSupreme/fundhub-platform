/** Bills and coins falling the whole clip, far behind the cards. */
const rainPieces = (g: Geo, f: number, seed: string, count: number, zRange: [number, number], alpha: number, bands?: [number, number][]): Piece[] => {
  const out: Piece[] = [];
  for (let i = 0; i < count; i++) {
    const r = (k: number) => random(`${seed}-${i}-${k}`);
    const near = r(1);
    const z = (zRange[0] + (zRange[1] - zRange[0]) * near) * g.u;
    const w = (130 + 110 * r(2)) * g.u;
    const span = g.H + 500 * g.u;
    const v = (3.2 + 3.4 * r(3)) * g.u;
    const p = (((r(4) * span + f * v) % span) + span) % span;
    const band = bands ? bands[i % bands.length] : ([0, g.W] as [number, number]);
    const phase = r(5) * Math.PI * 2;
    out.push({
      sx: band[0] + (band[1] - band[0]) * r(6) + Math.sin(f * 0.05 + phase) * 24 * g.u,
      sy: -250 * g.u + p,
      z,
      w,
      rz: -35 + 70 * r(7) + Math.sin(f * 0.06 + phase) * 14,
      rx: Math.sin(f * 0.08 + phase * 1.3) * 36,
      ry: Math.cos(f * 0.05 + phase) * 28,
      a: alpha * (0.55 + 0.45 * near),
      coin: r(8) < 0.3,
    });
  }
  return out;
};

/** A burst of bills and coins flying out from behind a slammed card toward the camera. */
const burstPieces = (g: Geo, f: number, at: number, cx: number, cy: number, w: number, h: number, seed: string, count: number, power: number): Piece[] => {
  const age = f - at + 1;
  if (age <= 0 || age > 30) return [];
  const out: Piece[] = [];
  for (let i = 0; i < count; i++) {
    const r = (k: number) => random(`${seed}-${i}-${k}`);
    // Out to the left and right (never straight up through the wordmark or down over the chip).
    const ang = (i % 2 === 0 ? 0 : Math.PI) + (r(1) - 0.5) * (Math.PI * 0.55);
    const dirX = Math.cos(ang);
    const dirY = Math.sin(ang) * 0.7;
    const v = (13 + 15 * r(2)) * g.u * power;
    const life = 20 + 8 * r(3);
    const t = age / life;
    if (t >= 1) continue;
    const zv = (8 + 10 * r(4)) * g.u;
    out.push({
      sx: cx + dirX * (w * 0.42 + v * age),
      sy: cy + dirY * (h * 0.42 + v * age) + 0.35 * g.u * age * age,
      // Capped just behind the card's face, so money never crosses in front of the approval.
      z: Math.min(-40 * g.u + zv * age, 18 * g.u),
      w: (110 + 80 * r(5)) * g.u,
      rz: -40 + 80 * r(6) + age * (r(7) - 0.5) * 18,
      rx: age * (8 + 10 * r(8)),
      ry: age * (r(9) - 0.5) * 22,
      a: Math.min(1, age / 2) * (1 - clamp01((t - 0.55) / 0.45)) * 0.95,
      coin: r(10) < 0.35,
    });
  }
  return out;
};

/** Bills and coins hanging and turning over the pile, slowly rising. */
const driftPieces = (g: Geo, f: number, seed: string, count: number, top: number, bottom: number): Piece[] => {
  const out: Piece[] = [];
  const span = bottom - top;
  for (let i = 0; i < count; i++) {
    const r = (k: number) => random(`${seed}-${i}-${k}`);
    const phase = r(5) * Math.PI * 2;
    const y = top + ((((r(4) * span - f * (1.2 + 1.6 * r(3)) * g.u) % span) + span) % span);
    out.push({
      sx: g.W * (0.04 + 0.92 * r(6)) + Math.sin(f * 0.04 + phase) * 30 * g.u,
      sy: y,
      z: (-200 + 100 * r(1)) * g.u,
      w: (120 + 80 * r(2)) * g.u,
      rz: -40 + 80 * r(7) + Math.sin(f * 0.05 + phase) * 10,
      rx: 18 + Math.sin(f * 0.06 + phase) * 22,
      ry: Math.cos(f * 0.045 + phase) * 26,
      a: 0.75,
      coin: r(8) < 0.3,
    });
  }
  return out;
};

