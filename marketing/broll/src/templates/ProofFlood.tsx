// The plan: which cards, where they rest, when they land

type FloodCardPlan = {a: FloodApproval; land: number; x: number; y: number; w: number; h: number; z: number; rx: number; ry: number; rz: number; from: {dx: number; dy: number; rx: number; ry: number; rz: number}};
type Beat = {cards: FloodApproval[]; s: number; exitAt: number; last: boolean; index: number};

const buildPlan = (props: ProofFloodProps, g: Geo) => {
  const beats: Beat[] = [];
  const raw = props.headline
    .map((h) => (Array.isArray(h) ? h : [h]).map((id) => BY_ID.get(id)).filter((a): a is FloodApproval => Boolean(a)).slice(0, 2))
    .filter((b) => b.length > 0);
  const weights = raw.map((b) => (b.length > 1 ? 1.45 : 1));
  const sum = weights.reduce((x, y) => x + y, 0) || 1;
  let s = INTRO;
  raw.forEach((cards, i) => {
    const span = ((PROOF_FLOOD_BASE - INTRO) * weights[i]) / sum;
    beats.push({cards, s, exitAt: s + span - SLAM, last: i === raw.length - 1, index: i});
    s += span;
  });
  const heroIds = new Set(beats.flatMap((b) => b.cards.map((a) => a.id)));
  const pool = props.approvals === 'all' ? FLOOD_APPROVALS : props.approvals.map((id) => BY_ID.get(id)).filter((a): a is FloodApproval => Boolean(a));
  const flood = pool.filter((a) => !heroIds.has(a.id));
  const lastSlam = beats.length > 0 ? beats[beats.length - 1].s : PROOF_FLOOD_BASE - 20;
  const n = flood.length;
  const cards: FloodCardPlan[] = flood.map((a, j) => {
    const r = (k: number) => random(`proof-flood-${a.id}-${k}`);
    const t = n > 1 ? j / (n - 1) : 0;
    const land = 3 + (lastSlam - 6 - 3) * t ** 1.1;
    const boost = 1 + 0.32 * clamp01(Math.log10(a.amount / 40000));
    const sw = g.pile.w * (0.88 + 0.2 * r(1)) * boost;
    const d = cardDims(a, sw, sw * 0.78);
    const hx = halton(j + 3, 2);
    const hy = halton(j + 3, 3);
    const inset = g.pile.sides ? d.w * 0.6 : d.w * 0.15;
    const x = Math.max(g.pile.x0 + inset, Math.min(g.pile.x1 - inset, g.pile.x0 + hx * (g.pile.x1 - g.pile.x0)));
    const yMin = g.pile.y0 + d.h / 2 + 6 * g.u;
    const yMax = g.pile.y1 - d.h / 2 - 14 * g.u;
    const y = yMin + hy * Math.max(0, yMax - yMin);
    const z = g.u * (-1380 + 1180 * t);
    const side = x < g.ox ? -1 : 1;
    return {
      a,
      land,
      x,
      y,
      w: sw,
      h: sw * 0.78,
      z,
      rx: -4 + 8 * r(2),
      ry: -5 + 10 * r(3),
      rz: -13 + 26 * r(4),
      from: {
        dx: side * (0.25 + 0.3 * r(5)),
        dy: -0.15 + 0.3 * r(6),
        rx: 40 + 30 * r(7),
        ry: side * (25 + 30 * r(8)),
        rz: (r(9) < 0.5 ? -1 : 1) * (45 + 50 * r(10)),
      },
    };
  });
  const total = cards.reduce((x, c) => x + c.a.amount, 0) + beats.reduce((x, b) => x + b.cards.reduce((y, a) => y + a.amount, 0), 0);
  return {beats, cards, total};
};

