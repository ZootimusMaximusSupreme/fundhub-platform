// ProofFlood: a flood of real approvals. Dozens of approval cards fly in out
// of the depth and pile up behind; the headline approvals slam to the front one
// at a time with a flash, a money burst and a big amount chip, then dock as a
// small trophy chip and drop back into the pile. A running total climbs while
// the cards land. It adds only the figures on screen: each card's amount joins
// the total the moment that card lands, so the last frame shows the sum of every
// approval in the clip.
//
// Every picture and figure is real: the crops and their amounts, lenders and
// products come from proofFloodApprovals.ts (generated by
// scripts/proof-flood-approvals.py from deck.json and approvals-manifest.json).
// A card with no lender in its picture shows its product instead. No name or
// face is added. A beat with two approvals (KeyBank) shows both $50,000
// approvals landing and their sum, never one $100,000 approval.
//
// Two formats from one component: "vertical" (1080x1920, ads, no words in the
// top 14% or bottom 35%) and "wide" (3840x2160, the horizontal VSL, words inside
// a 5% title-safe margin). Plain CSS 3D, no WebGL. Render with --gl=angle.

export type ProofFloodFormat = 'vertical' | 'wide';

export type ProofFloodProps = {
  format: ProofFloodFormat;
  /** Approval ids from proofFloodApprovals.ts that make up the flood, in landing order. "all" = all 46, smallest first. */
  approvals: string[] | 'all';
  /**
   * The headline beats, in order. Each beat is one id, or two ids that land together and add up
   * (["t-50k-keybank", "keybank-50k-loc"] = two $50,000 KeyBank approvals, $100,000 KeyBank).
   */
  headline: (string | string[])[];
  /** The running total of the approvals on screen. */
  showTotal: boolean;
  eyebrow: string;
  caption: string;
  /** 120 to 180 frames (4 to 6 seconds). Default 180. */
  durationInFrames?: number;
  showSafeZones?: boolean;
};

