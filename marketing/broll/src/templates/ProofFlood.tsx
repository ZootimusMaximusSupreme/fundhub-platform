const clamp01 = (v: number) => Math.max(0, Math.min(1, v));
const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
const easeOut = (t: number) => 1 - (1 - t) ** 3;
const inOut = Easing.inOut(Easing.cubic);

/** Low-discrepancy points: each new card lands far from the last one. */
const halton = (index: number, base: number): number => {
  let f = 1;
  let r = 0;
  let i = index;
  while (i > 0) {
    f /= base;
    r += f * (i % base);
    i = Math.floor(i / base);
  }
  return r;
};

const BY_ID = new Map(FLOOD_APPROVALS.map((a) => [a.id, a]));

/** "Barclays (JetBlue)" -> "Barclays". */
const lenderName = (a: FloodApproval): string | null => (a.lender ? a.lender.replace(/\s*\(.*\)\s*$/, '') : null);

/** The product without a repeated bank name, lines of credit in sentence case. */
const productName = (a: FloodApproval): string | null => {
  if (!a.product) return null;
  let p = a.product;
  const l = lenderName(a);
  if (l && p.toLowerCase().startsWith(`${l.toLowerCase()} `)) p = p.slice(l.length + 1);
  if (/line of credit/i.test(p)) p = p.charAt(0).toUpperCase() + p.slice(1).toLowerCase();
  return p;
};

/** What a card says next to its amount: the lender, or the product when the picture names no lender. */
const cardLabel = (a: FloodApproval): string => lenderName(a) ?? productName(a) ?? '';

type Dims = {w: number; h: number; iw: number; ih: number; pad: number; fs: number; fh: number; r: number};

/** A card fitted in a box: the whole picture (never cropped), a footer with the amount and the lender. */
const cardDims = (a: FloodApproval, boxW: number, boxH: number): Dims => {
  const s = Math.min(boxW / a.width, boxH / a.height);
  const iw = a.width * s;
  const ih = a.height * s;
  const pad = boxW * 0.03;
  const fs = Math.min(boxW * 0.052, iw * 0.085);
  const fh = fs * 2.05;
  return {w: iw + pad * 2, h: ih + pad + fh, iw, ih, pad, fs, fh, r: boxW * 0.035};
};

/** Where to put an element at depth z so it shows at screen point (sx, sy) at its own size. */
const place = (g: Geo, sx: number, sy: number, z: number) => {
  const k = (g.P - z) / g.P;
  return {x: g.ox + (sx - g.ox) * k, y: g.oy + (sy - g.oy) * k, k};
};

