#!/usr/bin/env node
// Bakes the lender names the LenderSlots B-roll spins through into
// src/data/lenders.ts, straight from the bank book:
//   docs/legacy-strong/lenders-legacy-strong.csv (column `name`)
//
// Every name below must match a `name` cell in that file exactly, or the
// script stops and writes nothing. No name is made up, shortened or reworded.
//
// Run from marketing/broll:  node scripts/bake-lenders.mjs

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const CSV = path.join(ROOT, 'docs/legacy-strong/lenders-legacy-strong.csv');
const OUT = path.resolve(HERE, '../src/data/lenders.ts');

// The 45 names the reels spin through (45 sits inside "the thirty to fifty
