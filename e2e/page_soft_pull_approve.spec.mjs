const query='?org=mock&client=mock&exp=1999999999&sig=mock';
const data={ok:true,contact:{first_name:'Dana'},consent:{valid:true},disclosure:{text:'I authorize Fundhub to request a soft credit inquiry for my funding assessment.',version:'2.1'}};
for(const width of [1440,390,320]) test(`approval iOS states and keyboard at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:1000});
 let release; const pending=new Promise(r=>release=r);
 await page.route('**/api/soft-pull-approve?**',async route=>{await pending;await route.fulfill({json:data});});
 await page.goto('/app/soft-pull-approve.html'+query);
 await expect(page.getByRole('status')).toContainText('Loading');
 await page.screenshot({path:`ops/workflows/build-evidence/client-portal-ios-redo/page_soft_pull_approve-${width}-loading.png`,fullPage:true});
 release();await expect(page.locator('#f')).toBeVisible();
 await expect(page.locator('body')).toHaveAttribute('data-client-ios','');
 await page.locator('#add_biz').focus();await page.keyboard.press('Enter');
 await expect(page.locator('[data-biz]')).toHaveCount(1);
 await page.locator('[data-rm]').focus();await page.keyboard.press('Enter');
 await expect(page.locator('[data-biz]')).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`ops/workflows/build-evidence/client-portal-ios-redo/page_soft_pull_approve-${width}-full.png`,fullPage:true});
 await page.goto('/app/soft-pull-approve.html');
 await expect(page.locator('#f')).toHaveCount(0);
 await expect(page.locator('.err')).toContainText('full link');
 await page.screenshot({path:`ops/workflows/build-evidence/client-portal-ios-redo/page_soft_pull_approve-${width}-empty-error.png`,fullPage:true});
});
