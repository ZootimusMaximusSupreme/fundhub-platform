// Builds fin-b22-sql-template-keys.json: the templates that only a SQL file writes (build time, never at
// run time). Run it with `node scripts/pulse/fin-b22-sql-template-keys.mjs --write`. The test
// fin-b22-flow-live.test.mjs rebuilds it and fails when the saved file is stale.

import fs from "node:fs";
import path from "node:path";

import { collect } from "../../../messaging/seed/collect.mjs";
import { isInactiveTemplateRow } from "./flow-gap-cases.mjs";
import { sqlOnlyTemplateKeys } from "./fin-b22-sql-template-keys.mjs";

export const SNAPSHOT_FILE = "src/pulse/catalog/proofs/fin-b22-sql-template-keys.json";

/**
 * { keys: [{ key, channel, approvedBySeed, inactive, files }] }
 * inactive: the catalog maps this template as having no sender (retired, dormant, or an alias-only key), so
 * a missing or switched-off copy of it hurts nobody and the live check leaves it alone.
 */
export function buildSqlTemplateSnapshot(root) {
  const { seedable } = collect(path.join(root, "fundhub-docs/sources"));
  const docKeys = new Set(seedable.map((t) => t.templateKey));
  const messages = JSON.parse(fs.readFileSync(path.join(root, "ops/workflows/coverage-every-surface-2026-10-10/messages.json"), "utf8"));
  const inactive = new Set(messages.filter(isInactiveTemplateRow).map((row) => row.surface.slice("template:".length)));
  return {
    note: "Generated by scripts/pulse/fin-b22-sql-template-keys.mjs. Templates written by SQL seed or migration files and not carried by the doc source. Do not edit by hand.",
    keys: sqlOnlyTemplateKeys(root, docKeys).map((row) => ({
      key: row.key,
      channel: row.channel,
      approvedBySeed: row.approvedBySeed,
      inactive: inactive.has(row.key),
      files: row.files,
    })),
  };
}
